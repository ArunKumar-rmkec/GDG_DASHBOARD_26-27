-- ============================================================================
-- V1__init_gdg_dashboard_schema.sql
-- Unified Relational Schema for GDGoC Campus Dashboard (M1 + M2)
-- Compatible with PostgreSQL 15+ and H2 (MODE=PostgreSQL)
-- ============================================================================

-- 1. members
CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    google_sub VARCHAR(255) UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    roll_number VARCHAR(100),
    department VARCHAR(150),
    academic_year INTEGER,
    phone VARCHAR(50),
    bio TEXT,
    skills TEXT,
    github_url VARCHAR(500),
    linkedin_url VARCHAR(500),
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    terminated_at TIMESTAMP WITH TIME ZONE,
    termination_reason TEXT,
    letter_window_expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. member_roles
CREATE TABLE member_roles (
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    role VARCHAR(64) NOT NULL,
    PRIMARY KEY (member_id, role)
);

-- 3. teams
CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL,
    description TEXT,
    parent_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE
);

-- 4. team_memberships
CREATE TABLE team_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    team_role VARCHAR(50) NOT NULL DEFAULT 'MEMBER',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMP WITH TIME ZONE,
    exit_reason VARCHAR(255)
);

CREATE INDEX idx_team_memberships_team_active ON team_memberships(team_id, active);
CREATE INDEX idx_team_memberships_member_active ON team_memberships(member_id, active);

-- 5. team_consensus_requests (3-GDG-Lead Consensus for Create / Delete / Rename Team)
CREATE TABLE team_consensus_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type VARCHAR(50) NOT NULL,
    target_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    proposed_name VARCHAR(200),
    proposed_description TEXT,
    parent_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    initiated_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    approval_count INTEGER NOT NULL DEFAULT 1,
    required_approvals INTEGER NOT NULL DEFAULT 3,
    executed_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    executed_at TIMESTAMP WITH TIME ZONE
);

-- 6. team_consensus_votes
CREATE TABLE team_consensus_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES team_consensus_requests(id) ON DELETE CASCADE,
    gdg_lead_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    approved BOOLEAN NOT NULL,
    comment TEXT,
    voted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_consensus_vote_request_lead UNIQUE (request_id, gdg_lead_id)
);

-- 7. permission_grants (Scheduled & Temporary Access Sharing)
CREATE TABLE permission_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    granted_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    grantee_member_id BIGINT REFERENCES members(id) ON DELETE CASCADE,
    grantee_role VARCHAR(64),
    permission_code VARCHAR(100) NOT NULL,
    scope_team_id BIGINT REFERENCES teams(id) ON DELETE CASCADE,
    scope_event_id BIGINT,
    cross_team_target_team_id BIGINT REFERENCES teams(id) ON DELETE CASCADE,
    approved_by_team_lead_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    approved_at TIMESTAMP WITH TIME ZONE,
    approval_comment TEXT,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_until TIMESTAMP WITH TIME ZONE,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_permission_grants_grantee ON permission_grants(grantee_member_id, status, revoked);

-- 8. member_change_requests (HR Dual-Authorization & Self-Service Bio-Data / Team Change Requests)
CREATE TABLE member_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_member_id BIGINT REFERENCES members(id) ON DELETE CASCADE,
    initiated_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    request_type VARCHAR(50) NOT NULL,
    payload_json TEXT,
    current_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    target_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    reason TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING_AUTHORIZATION',
    hr_lead_approved BOOLEAN NOT NULL DEFAULT FALSE,
    hr_lead_approved_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    hr_lead_approved_at TIMESTAMP WITH TIME ZONE,
    team_lead_approved BOOLEAN NOT NULL DEFAULT FALSE,
    team_lead_approved_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    team_lead_approved_at TIMESTAMP WITH TIME ZONE,
    gdg_lead_override_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    review_comment TEXT,
    executed_member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    executed_at TIMESTAMP WITH TIME ZONE
);

-- 9. collaborations (Sub-Team & Cross-Team Collaborations)
CREATE TABLE collaborations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    collaboration_type VARCHAR(50) NOT NULL DEFAULT 'CROSS_TEAM',
    lead_team_id BIGINT REFERENCES teams(id) ON DELETE CASCADE,
    created_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING_APPROVAL',
    deadline TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. collaboration_team_approvals
CREATE TABLE collaboration_team_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collaboration_id BIGINT NOT NULL REFERENCES collaborations(id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    approved_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    approval_status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    comment TEXT,
    approved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_collab_team_approval UNIQUE (collaboration_id, team_id)
);

-- 11. project_contributor_agreements (PCA Templates)
CREATE TABLE project_contributor_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(100) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    content_html TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 12. agreement_signatures (Issued & Signed PCAs)
CREATE TABLE agreement_signatures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id BIGINT NOT NULL REFERENCES project_contributor_agreements(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    issued_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    signature_text VARCHAR(500),
    signed_at TIMESTAMP WITH TIME ZONE,
    pdf_storage_key VARCHAR(500),
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_agreement_member UNIQUE (agreement_id, member_id)
);

-- 13. member_letters (Appointment, Recommendation, Appreciation, Termination, Contributor Agreement)
CREATE TABLE member_letters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    letter_type VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    content_html TEXT NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    issued_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    download_count INTEGER NOT NULL DEFAULT 0,
    last_downloaded_at TIMESTAMP WITH TIME ZONE
);

-- 14. tasks (M2 Task Assigning & Tracking Core)
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    assignment_type VARCHAR(64) NOT NULL,
    assignor_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    assignee_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    source_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    target_team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    collaboration_id BIGINT REFERENCES collaborations(id) ON DELETE SET NULL,
    priority VARCHAR(32) NOT NULL DEFAULT 'MEDIUM',
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(64) NOT NULL DEFAULT 'ASSIGNED',
    progress_percentage INTEGER NOT NULL DEFAULT 0,
    cross_team_approved_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    cross_team_approval_comment TEXT,
    cross_team_approved_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_tasks_assignee ON tasks(assignee_id, status);
CREATE INDEX idx_tasks_target_team ON tasks(target_team_id, status);

-- 15. task_progress_logs
CREATE TABLE task_progress_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    updated_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    previous_progress INTEGER NOT NULL,
    new_progress INTEGER NOT NULL,
    previous_status VARCHAR(64) NOT NULL,
    new_status VARCHAR(64) NOT NULL,
    note TEXT,
    evidence_url VARCHAR(500),
    logged_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 16. events (M2 Event Management)
CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    event_date TIMESTAMP WITH TIME ZONE NOT NULL,
    venue VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'UPCOMING',
    created_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 17. event_leads (Event-Specific Leads & Event Team Members)
CREATE TABLE event_leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    event_role VARCHAR(64) NOT NULL DEFAULT 'EVENT_LEAD',
    assigned_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_event_lead_member UNIQUE (event_id, member_id)
);

-- 18. event_attendances (Barcode & Manual Check-In)
CREATE TABLE event_attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    participant_name VARCHAR(255) NOT NULL,
    participant_email VARCHAR(255) NOT NULL,
    roll_number VARCHAR(100),
    barcode_token VARCHAR(255),
    entry_method VARCHAR(32) NOT NULL,
    checked_in_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    checked_in_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_attendance_event_email UNIQUE (event_id, participant_email),
    CONSTRAINT uk_attendance_event_barcode UNIQUE (event_id, barcode_token)
);

-- 19. certificates (Generated & Saved PDF Event Certificates)
CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    attendance_id BIGINT NOT NULL REFERENCES event_attendances(id) ON DELETE CASCADE,
    recipient_name VARCHAR(255) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    template_title VARCHAR(255) NOT NULL DEFAULT 'Certificate of Participation',
    certificate_code VARCHAR(128) NOT NULL UNIQUE,
    storage_key VARCHAR(500) NOT NULL,
    generated_by_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    generated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_certificate_event_attendance UNIQUE (event_id, attendance_id)
);

-- 20. email_dispatch_logs (Mail Certificates, CC/BCC & Bounce-Back Webhook Tracking)
CREATE TABLE email_dispatch_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT REFERENCES events(id) ON DELETE CASCADE,
    certificate_id BIGINT REFERENCES certificates(id) ON DELETE SET NULL,
    recipient_email VARCHAR(255) NOT NULL,
    cc_emails TEXT,
    bcc_emails TEXT,
    subject VARCHAR(500),
    body TEXT,
    provider_message_id VARCHAR(255) NOT NULL UNIQUE,
    delivery_status VARCHAR(50) NOT NULL DEFAULT 'SENT',
    bounce_reason TEXT,
    bounced_at TIMESTAMP WITH TIME ZONE,
    sent_by_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_email_dispatch_event ON email_dispatch_logs(event_id, delivery_status);
